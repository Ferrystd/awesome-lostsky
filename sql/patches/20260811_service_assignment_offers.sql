CREATE TABLE `team_service_assignment_offer` (
    `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `team_id` INT UNSIGNED NOT NULL,
    `service_id` INT UNSIGNED NOT NULL,
    `customer_id` INT UNSIGNED NOT NULL,
    `holder_entity_id` INT UNSIGNED NOT NULL,
    `entitlement_id` INT UNSIGNED NOT NULL,
    `target_handler_entity_id` INT UNSIGNED NOT NULL,
    `quantity` DECIMAL(18,4) NOT NULL DEFAULT 1.0000,
    `status` TINYINT NOT NULL DEFAULT 1,
    `memo` TEXT NULL,
    `field_values` JSON NULL,
    `total_price` DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    `cost` DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    `handler_cut` DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    `sender_cut` DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    `cs_cut` DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    `team_cut` DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    `expire_time` INT UNSIGNED NOT NULL DEFAULT 0,
    `service_instance_id` INT UNSIGNED NULL DEFAULT NULL,
    `decided_by_entity_id` INT UNSIGNED NULL DEFAULT NULL,
    `decision_reason` VARCHAR(500) NULL DEFAULT NULL,
    `decided_at` INT UNSIGNED NULL DEFAULT NULL,
    `idempotency_key` VARCHAR(100) NULL DEFAULT NULL,
    `create_time` INT UNSIGNED NOT NULL DEFAULT 0,
    `update_time` INT UNSIGNED NOT NULL DEFAULT 0,
    `delete_time` INT UNSIGNED NULL DEFAULT NULL,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_assignment_offer_instance` (`service_instance_id`),
    UNIQUE KEY `uk_assignment_offer_idempotency` (`team_id`, `holder_entity_id`, `idempotency_key`),
    KEY `idx_assignment_offer_target` (`team_id`, `target_handler_entity_id`, `status`, `expire_time`, `id`),
    KEY `idx_assignment_offer_customer` (`customer_id`, `entitlement_id`, `id`),
    CONSTRAINT `fk_assignment_offer_team` FOREIGN KEY (`team_id`) REFERENCES `team` (`id`),
    CONSTRAINT `fk_assignment_offer_service` FOREIGN KEY (`service_id`) REFERENCES `team_service` (`id`),
    CONSTRAINT `fk_assignment_offer_customer` FOREIGN KEY (`customer_id`) REFERENCES `team_customer` (`id`),
    CONSTRAINT `fk_assignment_offer_holder` FOREIGN KEY (`holder_entity_id`) REFERENCES `entity` (`id`),
    CONSTRAINT `fk_assignment_offer_entitlement` FOREIGN KEY (`entitlement_id`) REFERENCES `team_service_entitlement` (`id`),
    CONSTRAINT `fk_assignment_offer_target` FOREIGN KEY (`target_handler_entity_id`) REFERENCES `entity` (`id`),
    CONSTRAINT `fk_assignment_offer_instance` FOREIGN KEY (`service_instance_id`) REFERENCES `team_service_instance` (`id`),
    CONSTRAINT `fk_assignment_offer_decider` FOREIGN KEY (`decided_by_entity_id`) REFERENCES `entity` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Customer指定接单邀请';
